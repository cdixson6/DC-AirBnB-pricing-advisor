import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import { fileURLToPath } from 'url';
import fs from 'fs';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  // In AI Studio, the dev server must always bind to port 3000 (0.0.0.0:3000)
  const PORT = 3000;

  app.use(express.json({ limit: '10mb' }));

  // Gemini Owner Memo endpoint
  app.post('/api/gemini/generate-memo', async (req, res) => {
    try {
      const { computedData } = req.body;
      if (!computedData) {
        return res.status(400).json({ error: 'Missing computedData in request body' });
      }

      // Built-in free executive memo generator using strictly computed numbers
      const p = computedData.propertyIntake || {};
        const nums = computedData.computedPricingNumbers || {};
        const rev = computedData.computedOccupancyAndRevenue || {};
        const comp = computedData.compSetAnalysis || {};
        const uplifts = (computedData.computedAmenityUplifts || [])
          .filter((u: any) => u.eligible_5CompsPerGroup)
          .map((u: any) => `• ${u.amenity}: ${u.percentageDifference > 0 ? '+' : ''}${u.percentageDifference}% ($${u.dollarDifferencePerNight}/nt diff)`)
          .join('\n') || '• No statistically significant amenity uplifts detected in current comp set (minimum 5 comps per group).';

        const fallbackMemo =
`# Executive Owner Pricing & Revenue Advisory Memo
**Client Property:** ${p.neighborhood || 'Washington, DC'} • ${p.roomType || 'Entire home/apt'} • ${p.bedrooms === 0 ? 'Studio' : p.bedrooms + ' BR'} • ${p.bathrooms || 1} BA
**Market Snapshot:** Inside Airbnb Washington, D.C. Verified Public Dataset

---

### 1. Executive Summary & Recommended Nightly Rate
Based on a rigorous benchmark of ${comp.totalMatchingComps || 0} verified active comps in ${p.neighborhood}, we recommend an opening benchmark rate of **$${nums.recommendedNightlyRate_Median || 0} per night** (median of matching comp set).
- **Conservative Market Floor (25th Percentile):** $${nums.percentile_25th_Conservative || 0} / night
- **Recommended Benchmark (50th Percentile):** $${nums.recommendedNightlyRate_Median || 0} / night
- **Peak / High-Demand Ceiling (75th Percentile):** $${nums.percentile_75th_Peak || 0} / night
- **Comp Range:** $${nums.minimumCompPrice || 0} to $${nums.maximumCompPrice || 0} per night (Average: $${nums.averageCompPrice || 0})

---

### 2. Annual Revenue Projections & DC 90-Night STR Cap Analysis
- **Median Market Occupancy:** ${rev.medianAnnualOccupancyNights || 0} booked nights/year
- **Gross Revenue Potential (Hosted / Owner Present):** **$${(rev.projectedAnnualRevenueFullHosted || 0).toLocaleString()} / year**
- **DC Statutory 90-Night Cap Status:** ${rev.dcCapApplies ? 'APPLIES (Owner Absent / Vacation Rental)' : 'EXEMPT (Owner Residing On-Site)'}
${rev.dcCapApplies ? `- **Capped Gross Annual Revenue (90 Nights Max):** **$${(rev.projectedAnnualRevenueCappedAt90Nights || 0).toLocaleString()} / year**\n- **Estimated Gross Revenue Impact from 90-Night Cap:** -$${(rev.revenueLossFrom90NightCap || 0).toLocaleString()} / year` : '- Because the owner lives on-site during stays, the property is classified as a primary Short-Term Rental and qualifies for full 365-day potential without the 90-night limit.'}

---

### 3. Comp Set Context & Property Benchmark
- **Total Validated Comps:** ${comp.totalMatchingComps || 0} listings in ${p.neighborhood}
- **Property Type Rule:** ${comp.condoFilterRuleUsed || 'Benchmark includes all property types.'}
- **Condo Representation:** ${comp.condoCompsSampled || 0} condo comps analyzed (15-comp threshold ${comp.condoThresholdMet ? 'met' : 'not met'}).

---

### 4. Amenity Uplift Opportunities
Verified price differentials from active neighborhood listings with vs. without key amenities:
${uplifts}

---

### 5. Regulatory & Compliance Next Steps
1. **DC DLCP Short-Term Rental License:** Required prior to listing on Airbnb or VRBO ($104.50 biennial registration fee).
2. **Primary Residence Verification:** Confirm property is registered under the owner\'s Homestead Deduction.
3. **Condo / HOA By-Laws:** Review governing condominium bylaws for short-term rental restrictions or minimum lease duration rules.

*(Generated by DC Airbnb Pricing Advisor. Strictly reflects verified Inside Airbnb DC snapshot numbers.)*`;

      // If Gemini API is configured, try calling it; otherwise return computed memo immediately
      if (process.env.GEMINI_API_KEY) {
        try {
          const ai = new GoogleGenAI({
            apiKey: process.env.GEMINI_API_KEY,
            httpOptions: {
              headers: {
                'User-Agent': 'aistudio-build',
              },
            },
          });

          const systemInstruction =
            'You explain pricing results to a property owner. Use only the numbers in the JSON provided. ' +
            'Do not add, estimate, or round any number differently. If something is not in the JSON, say it is not in the data. ' +
            'Write in a clear, executive, high-trust tone suitable for a senior Washington, DC property management advisor advising a client. ' +
            'Structure the memo with concise sections: ' +
            '1. Executive Summary & Recommended Nightly Rate (reference the median price and 25th-75th percentile range). ' +
            '2. Annual Revenue Projections & DC 90-Night STR Cap Analysis (detail the live-in vs absent owner figures). ' +
            '3. Comp Set Context & Property Type Benchmark (explain how many comps were evaluated and whether condo or all types were matched). ' +
            '4. Amenity Uplift Opportunities (highlight the verified comp uplifts from the data). ' +
            '5. Regulatory & Compliance Next Steps (DC Short-Term Rental License, Primary Residence, Condo By-Laws).';

          const prompt = `Here is the strictly computed comp analysis data in JSON for the homeowner's property:\n\n${JSON.stringify(computedData, null, 2)}\n\nPlease compose a tailored, professional Owner Pricing & Revenue Advisory Memo based strictly on these verified numbers.`;

          const response = await ai.models.generateContent({
            model: 'gemini-2.5-flash',
            contents: prompt,
            config: {
              systemInstruction,
            },
          });

          if (response.text) {
            return res.json({ memo: response.text });
          }
        } catch (apiErr: any) {
          console.warn('Gemini API call failed or busy, using verified computed memo fallback:', apiErr?.message);
        }
      }

      // Return the verified computed memo (100% free, zero cost, instant response)
      return res.json({ memo: fallbackMemo });
    } catch (err: any) {
      console.error('Error generating memo:', err);
      return res.status(500).json({
        error: err?.message || 'Failed to generate advisory memo.'
      });
    }
  });

  // Explicit static file serving for /data
  const publicDataDir = path.resolve(__dirname, 'public/data');
  const rootDataDir = path.resolve(__dirname, 'data');
  app.use('/data', express.static(publicDataDir));
  app.use('/data', express.static(rootDataDir));

  // Fallback endpoint to ensure /data/dc_listings_clean.csv is always directly fetchable
  app.get('/data/dc_listings_clean.csv', (_req, res) => {
    const candidate1 = path.join(publicDataDir, 'dc_listings_clean.csv');
    const candidate2 = path.join(rootDataDir, 'dc_listings_clean.csv');
    if (fs.existsSync(candidate1)) {
      return res.sendFile(candidate1);
    } else if (fs.existsSync(candidate2)) {
      return res.sendFile(candidate2);
    } else {
      return res.status(404).send('dc_listings_clean.csv not found');
    }
  });

  // Vite dev middleware vs production static
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: {
        middlewareMode: true,
        hmr: false,
      },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist/index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`DC Airbnb Pricing Advisor server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer();
